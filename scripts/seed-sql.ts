// Writes seed/seed.sql from the starter catalogue in src/data/catalogue.ts.
// Run with: npm run db:seed:local (or db:seed:remote). Safe to re-run: rows that already
// exist are skipped, never overwritten, so edits made in the admin are kept.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { seedBrands, seedCategories, seedProducts } from "../src/data/catalogue.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const sql = (value: string | number | boolean | null | undefined): string => {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  if (typeof value === "number") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
};
const json = (value: unknown) => sql(JSON.stringify(value));
// Starter photos ship with the site in public/, so they are referenced by path.
const imagePath = (src: string) => `/${src.replace(/^\//, "")}`;
const escapeHtml = (text: string) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const topCategory = (slug: string) =>
  `(SELECT id FROM categories WHERE parent_id IS NULL AND slug = ${sql(slug)})`;

const lines: string[] = ["-- Generated by scripts/seed-sql.ts. Do not edit by hand."];

for (const c of seedCategories) {
  lines.push(
    `INSERT OR IGNORE INTO categories (parent_id, slug, title, summary, image_url, image_alt, tone, show_on_home, made_in_house, sort_order) VALUES (NULL, ${sql(c.slug)}, ${sql(c.title)}, ${sql(c.summary)}, ${sql(imagePath(c.image.src))}, ${sql(c.image.alt)}, ${sql(c.tone)}, ${sql(c.showOnHome)}, ${sql(c.madeInHouse)}, ${sql(c.order)});`,
  );
}

for (const b of seedBrands) {
  lines.push(
    `INSERT OR IGNORE INTO brands (slug, name, in_house, sort_order) VALUES (${sql(b.slug)}, ${sql(b.name)}, ${sql(b.inHouse)}, ${sql(b.order)});`,
  );
}

for (const p of seedProducts) {
  const brand = p.brand ? `(SELECT id FROM brands WHERE slug = ${sql(p.brand)})` : "NULL";
  const description = p.description.map((text) => `<p>${escapeHtml(text)}</p>`).join("");
  lines.push(
    `INSERT OR IGNORE INTO products (category_id, brand_id, slug, title, summary, description, key_features, specifications, variants, is_sample, sort_order) VALUES (${topCategory(p.category)}, ${brand}, ${sql(p.slug)}, ${sql(p.title)}, ${sql(p.summary)}, ${sql(description)}, ${json(p.keyFeatures)}, ${json(p.specifications)}, ${json(p.variants)}, ${sql(p.isSample)}, ${sql(p.order)});`,
  );
  const product = `(SELECT id FROM products WHERE category_id = ${topCategory(p.category)} AND slug = ${sql(p.slug)})`;
  p.images.forEach((image, i) => {
    lines.push(
      `INSERT INTO product_images (product_id, image_url, alt, sort_order) SELECT ${product}, ${sql(imagePath(image.src))}, ${sql(image.alt)}, ${(i + 1) * 10} WHERE NOT EXISTS (SELECT 1 FROM product_images WHERE product_id = ${product} AND image_url = ${sql(imagePath(image.src))});`,
    );
  });
}

const out = join(root, "seed", "seed.sql");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${lines.length - 1} statements to ${out}`);
